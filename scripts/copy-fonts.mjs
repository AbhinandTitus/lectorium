// Copies the bundled reading fonts from Fontsource packages into
// public/fonts and generates public/reader-fonts.css. Run explicitly:
//   node scripts/copy-fonts.mjs
// Outputs are committed so the app builds offline. Licenses (OFL) are
// copied alongside the files.

import { copyFileSync, mkdirSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "public", "fonts");
mkdirSync(outDir, { recursive: true });

// family -> package, weights/styles to bundle (latin + malayalam subsets)
const PLAN = [
  {
    family: "Literata",
    pkg: "@fontsource/literata",
    files: [
      "literata-latin-400-normal.woff2",
      "literata-latin-400-italic.woff2",
      "literata-latin-700-normal.woff2",
      "literata-latin-ext-400-normal.woff2",
    ],
    faces: [
      { file: "literata-latin-400-normal.woff2", weight: 400, style: "normal" },
      { file: "literata-latin-400-italic.woff2", weight: 400, style: "italic" },
      { file: "literata-latin-700-normal.woff2", weight: 700, style: "normal" },
    ],
  },
  {
    family: "Noto Serif Malayalam",
    pkg: "@fontsource/noto-serif-malayalam",
    files: ["noto-serif-malayalam-malayalam-400-normal.woff2", "noto-serif-malayalam-malayalam-700-normal.woff2"],
    faces: [
      { file: "noto-serif-malayalam-malayalam-400-normal.woff2", weight: 400, style: "normal" },
      { file: "noto-serif-malayalam-malayalam-700-normal.woff2", weight: 700, style: "normal" },
    ],
  },
  {
    family: "Noto Sans Malayalam",
    pkg: "@fontsource/noto-sans-malayalam",
    files: ["noto-sans-malayalam-malayalam-400-normal.woff2", "noto-sans-malayalam-malayalam-700-normal.woff2"],
    faces: [
      { file: "noto-sans-malayalam-malayalam-400-normal.woff2", weight: 400, style: "normal" },
      { file: "noto-sans-malayalam-malayalam-700-normal.woff2", weight: 700, style: "normal" },
    ],
  },
  {
    family: "Noto Sans",
    pkg: "@fontsource/noto-sans",
    files: ["noto-sans-latin-400-normal.woff2", "noto-sans-latin-700-normal.woff2"],
    faces: [
      { file: "noto-sans-latin-400-normal.woff2", weight: 400, style: "normal" },
      { file: "noto-sans-latin-700-normal.woff2", weight: 700, style: "normal" },
    ],
  },
  {
    family: "Inter",
    pkg: "@fontsource-variable/inter",
    files: ["inter-latin-wght-normal.woff2"],
    faces: [{ file: "inter-latin-wght-normal.woff2", weight: "100 900", style: "normal" }],
  },
];

let css = "/* generated by scripts/copy-fonts.mjs — bundled OFL fonts, no network */\n";

for (const { family, pkg, files, faces } of PLAN) {
  const filesDir = join(root, "node_modules", pkg, "files");
  for (const f of files) {
    const src = join(filesDir, f);
    if (!existsSync(src)) {
      console.error(`missing ${src}`);
      console.error("available:", readdirSync(filesDir).slice(0, 10).join(", "));
      process.exit(1);
    }
    copyFileSync(src, join(outDir, f));
    console.log("copied", f);
  }
  // license
  const licenseSrc = join(root, "node_modules", pkg, "LICENSE");
  if (existsSync(licenseSrc)) {
    copyFileSync(licenseSrc, join(outDir, `LICENSE-${family.replace(/ /g, "-")}.txt`));
  }
  for (const face of faces) {
    css += `@font-face {
  font-family: "${family}";
  src: url("/fonts/${face.file}") format("woff2");
  font-weight: ${face.weight};
  font-style: ${face.style};
  font-display: swap;
}
`;
  }
}

writeFileSync(join(root, "public", "reader-fonts.css"), css);
console.log("wrote public/reader-fonts.css");
